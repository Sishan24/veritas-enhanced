"""Tests for passage-split mode (Task 2).

Covers:
- pair mode DOES have evidence passage overlap across splits (documents the leak).
- passage mode has ZERO passage overlap.
- All 3 labels are present in every passage-mode split.
- assert_no_passage_overlap raises when overlap exists.
- assert_no_passage_overlap passes when there is no overlap.
"""
import pytest

from ml.make_sample_data import (
    assert_no_passage_overlap,
    capital_facts,
    firm_facts,
    journalism_facts,
    make_passage_split,
    make_rows,
)
import random


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _get_pair_mode_rows(seed=42):
    """Return (train, dev, test) rows generated by the original pair-mode logic."""
    rng = random.Random(seed)
    cap  = capital_facts()
    firm = firm_facts(rng)
    jour = journalism_facts()
    combined = cap + firm + jour + jour + jour + jour

    train_rows = make_rows(rng, 8000, combined)
    dev_rows   = make_rows(rng,  900, combined)
    test_rows  = make_rows(rng,  900, combined)
    return train_rows, dev_rows, test_rows


# ---------------------------------------------------------------------------
# 1. Document that pair mode HAS overlap (the data-leakage test)
# ---------------------------------------------------------------------------

class TestPairModeLeakage:
    def test_pair_mode_train_test_evidence_overlaps(self):
        """Pair mode: test evidence passages are a subset of train passages (leakage exists)."""
        train, _, test = _get_pair_mode_rows()
        ev_train = {r["evidence"] for r in train}
        ev_test  = {r["evidence"] for r in test}
        overlap = ev_train & ev_test
        # We expect significant overlap — assert it is non-zero to document the leak
        assert len(overlap) > 0, (
            "Expected evidence-passage overlap in pair mode (data leakage), but found none. "
            "If this changes, re-evaluate the train/test protocol."
        )

    def test_pair_mode_train_dev_evidence_overlaps(self):
        """Pair mode: dev evidence passages overlap with train (leakage exists)."""
        train, dev, _ = _get_pair_mode_rows()
        ev_train = {r["evidence"] for r in train}
        ev_dev   = {r["evidence"] for r in dev}
        overlap = ev_train & ev_dev
        assert len(overlap) > 0, (
            "Expected evidence-passage overlap in pair mode (data leakage), but found none."
        )

    def test_pair_mode_overlap_is_large(self):
        """Pair mode: >50% of test passages also appear in train (quantifies the leak)."""
        train, _, test = _get_pair_mode_rows()
        ev_train = {r["evidence"] for r in train}
        ev_test  = {r["evidence"] for r in test}
        overlap_frac = len(ev_train & ev_test) / max(len(ev_test), 1)
        assert overlap_frac > 0.5, (
            f"Expected >50% test passage overlap in pair mode, got {overlap_frac:.2%}"
        )


# ---------------------------------------------------------------------------
# 2. Passage mode: zero overlap
# ---------------------------------------------------------------------------

class TestPassageModeNoOverlap:
    @pytest.fixture(scope="class")
    @classmethod
    def passage_data(cls, tmp_path_factory):
        """Generate passage-split data once for the whole class."""
        out = tmp_path_factory.mktemp("passage_split")
        train, dev, test, lc = make_passage_split(seed=42, out_dir=str(out))
        return train, dev, test, lc

    def test_zero_train_dev_overlap(self, passage_data):
        train, dev, test, _ = passage_data
        ev_train = {r["evidence"] for r in train}
        ev_dev   = {r["evidence"] for r in dev}
        assert len(ev_train & ev_dev) == 0, "train∩dev overlap found in passage mode"

    def test_zero_train_test_overlap(self, passage_data):
        train, dev, test, _ = passage_data
        ev_train = {r["evidence"] for r in train}
        ev_test  = {r["evidence"] for r in test}
        assert len(ev_train & ev_test) == 0, "train∩test overlap found in passage mode"

    def test_zero_dev_test_overlap(self, passage_data):
        train, dev, test, _ = passage_data
        ev_dev  = {r["evidence"] for r in dev}
        ev_test = {r["evidence"] for r in test}
        assert len(ev_dev & ev_test) == 0, "dev∩test overlap found in passage mode"

    def test_all_labels_in_train(self, passage_data):
        train, _, _, _ = passage_data
        labels = {r["label"] for r in train}
        assert labels == {"SUPPORTED", "REFUTED", "NOT_ENOUGH_INFO"}, (
            "Missing labels in train: " + str({"SUPPORTED", "REFUTED", "NOT_ENOUGH_INFO"} - labels)
        )

    def test_all_labels_in_dev(self, passage_data):
        _, dev, _, _ = passage_data
        labels = {r["label"] for r in dev}
        assert labels == {"SUPPORTED", "REFUTED", "NOT_ENOUGH_INFO"}, (
            "Missing labels in dev: " + str({"SUPPORTED", "REFUTED", "NOT_ENOUGH_INFO"} - labels)
        )

    def test_all_labels_in_test(self, passage_data):
        _, _, test, _ = passage_data
        labels = {r["label"] for r in test}
        assert labels == {"SUPPORTED", "REFUTED", "NOT_ENOUGH_INFO"}, (
            "Missing labels in test: " + str({"SUPPORTED", "REFUTED", "NOT_ENOUGH_INFO"} - labels)
        )

    def test_files_written_to_disk(self, passage_data, tmp_path_factory):
        """make_passage_split writes the expected files."""
        from pathlib import Path
        out = tmp_path_factory.mktemp("passage_split_files")
        make_passage_split(seed=42, out_dir=str(out))
        for fname in ("train.jsonl", "dev.jsonl", "test.jsonl", "evidence.jsonl"):
            assert (out / fname).exists(), f"{fname} not written"


# ---------------------------------------------------------------------------
# 3. assert_no_passage_overlap unit tests
# ---------------------------------------------------------------------------

class TestAssertNoPassageOverlap:
    def _make_rows(self, evidences, label="SUPPORTED"):
        return [{"claim": "c", "evidence": e, "label": label} for e in evidences]

    def test_raises_on_train_dev_overlap(self):
        train = self._make_rows(["ev_a", "ev_b"])
        dev   = self._make_rows(["ev_b", "ev_c"])  # ev_b overlaps
        test  = self._make_rows(["ev_d"])
        with pytest.raises(AssertionError, match="train"):
            assert_no_passage_overlap(train, dev, test)

    def test_raises_on_train_test_overlap(self):
        train = self._make_rows(["ev_a", "ev_b"])
        dev   = self._make_rows(["ev_c"])
        test  = self._make_rows(["ev_a", "ev_d"])  # ev_a overlaps
        with pytest.raises(AssertionError, match="train"):
            assert_no_passage_overlap(train, dev, test)

    def test_raises_on_dev_test_overlap(self):
        train = self._make_rows(["ev_a"])
        dev   = self._make_rows(["ev_b", "ev_c"])
        test  = self._make_rows(["ev_c", "ev_d"])  # ev_c overlaps
        with pytest.raises(AssertionError, match="dev"):
            assert_no_passage_overlap(train, dev, test)

    def test_passes_when_no_overlap(self):
        train = self._make_rows(["ev_a", "ev_b"])
        dev   = self._make_rows(["ev_c"])
        test  = self._make_rows(["ev_d"])
        # Should not raise
        assert_no_passage_overlap(train, dev, test)
